//! Harbor the way CI and clients use it: the admin creates a run-tagged project and a project
//! robot, the robot pushes a generated image through the registry API, a pull returns the same
//! bytes, and the repository, robot and project are deleted and checked gone. The admin is only
//! used to make and remove tagged projects.

use reqwest::Method;
use serde_json::json;

use super::oci::{digest, image, tar_first_file, Registry};
use crate::{
    ctx::{chain, json as get_json, need_secret, poll, send, At, Ctx, Fail, Scope, R},
    report::Flow,
    svc::{tagged, url},
};

const APP: &str = "harbor";
const REPO: &str = "app";
const TAG: &str = "v1";

struct Hb {
    base: String,
    pw: String,
}

impl Hb {
    fn connect() -> R<Self> {
        Ok(Hb { base: url("HARBOR_URL", "harbor"), pw: need_secret(APP, "e2e-harbor", "password")? })
    }

    fn api(&self, ctx: &Ctx, m: Method, path: &str) -> reqwest::RequestBuilder {
        ctx.http.request(m, format!("{}/api/v2.0{path}", self.base)).basic_auth("admin", Some(&self.pw))
    }

    async fn projects(&self, ctx: &Ctx, scope: &Scope) -> R<Vec<(i64, String)>> {
        let v = get_json(self.api(ctx, Method::GET, "/projects?name=e2e-&page_size=100"), APP, "list projects").await?;
        Ok(v.as_array().into_iter().flatten().filter_map(|p| Some((p["project_id"].as_i64()?, p["name"].as_str()?.to_string()))).filter(|(_, n)| scope.hit(n)).collect())
    }

    /// Delete a tagged project with everything in it: repositories, robots, then the project.
    async fn remove_project(&self, ctx: &Ctx, id: i64, name: &str) -> R<()> {
        tagged(APP, name)?;
        let repos = get_json(self.api(ctx, Method::GET, &format!("/projects/{name}/repositories?page_size=100")), APP, "list repositories").await?;
        for r in repos.as_array().into_iter().flatten().filter_map(|r| r["name"].as_str()) {
            let short = r.strip_prefix(&format!("{name}/")).unwrap_or(r).replace('/', "%252F");
            send(self.api(ctx, Method::DELETE, &format!("/projects/{name}/repositories/{short}")), APP, "delete repository").await?;
        }
        let robots = get_json(self.api(ctx, Method::GET, &format!("/robots?q=Level%3Dproject%2CProjectID%3D{id}&page_size=100")), APP, "list robots").await?;
        for r in robots.as_array().into_iter().flatten().filter_map(|r| r["id"].as_i64()) {
            send(self.api(ctx, Method::DELETE, &format!("/robots/{r}")), APP, "delete robot").await?;
        }
        send(self.api(ctx, Method::DELETE, &format!("/projects/{name}")), APP, "delete project").await?;
        Ok(())
    }
}

pub async fn push_pull(ctx: &Ctx, f: &mut Flow) -> R<()> {
    let hb = Hb::connect()?;
    let m = tagged(APP, &ctx.marker)?;
    send(hb.api(ctx, Method::POST, "/projects").json(&json!({ "project_name": m, "metadata": { "public": "false" } })), APP, "create project").await?;
    f.ok(APP, "tagged project created", m.to_string());

    let robot = get_json(
        hb.api(ctx, Method::POST, "/robots").json(&json!({
            "name": "push", "description": format!("e2e {m}"), "level": "project", "duration": 1,
            "permissions": [{ "kind": "project", "namespace": m, "access": [
                { "resource": "repository", "action": "push" }, { "resource": "repository", "action": "pull" },
                { "resource": "artifact", "action": "read" }, { "resource": "tag", "action": "create" }, { "resource": "tag", "action": "list" }] }],
        })),
        APP,
        "create robot",
    )
    .await?;
    let (rname, rsecret) = (robot["name"].as_str().at(APP, "robot name")?.to_string(), robot["secret"].as_str().at(APP, "robot secret")?.to_string());
    f.ok(APP, "project robot created", rname.clone());

    let repo = format!("{m}/{REPO}");
    let reg = Registry::login(ctx, APP, &hb.base, &rname, &rsecret, &repo).await?;
    let text = format!("generated by e2e run {m}\n");
    let img = image(&text);
    for blob in [&img.layer, &img.config] {
        reg.push_blob(ctx, APP, &repo, blob).await?;
    }
    reg.push_manifest(ctx, APP, &repo, TAG, &img.manifest).await?;
    f.ok(APP, "image pushed with the robot", format!("{repo}:{TAG}, {} blobs + manifest", 2));

    let (manifest, dig) = reg.pull_manifest(ctx, APP, &repo, TAG).await?;
    if manifest != img.manifest || dig != digest(&img.manifest) {
        return Err(Fail::new(APP, "pull manifest", format!("registry digest {dig}, pushed {}", digest(&img.manifest))));
    }
    let layer = reg.pull_blob(ctx, APP, &repo, &img.layer.0).await?;
    if tar_first_file(&layer).map(|(_, c)| c) != Some(text.clone().into_bytes()) {
        return Err(Fail::new(APP, "pull layer", "the layer does not hold the pushed file"));
    }
    f.ok(APP, "pulled back the same bytes", format!("manifest {}", &dig[..19]));

    let arts = poll(APP, "artifact listed", std::time::Duration::from_secs(30), std::time::Duration::from_secs(2), || async {
        let v = get_json(hb.api(ctx, Method::GET, &format!("/projects/{m}/repositories/{REPO}/artifacts")), APP, "list artifacts").await?;
        Ok(v.as_array().filter(|a| !a.is_empty()).cloned())
    })
    .await?;
    let tags: Vec<&str> = arts.iter().flat_map(|a| a["tags"].as_array().into_iter().flatten()).filter_map(|t| t["name"].as_str()).collect();
    if !tags.contains(&TAG) {
        return Err(Fail::new(APP, "artifact", format!("tags {tags:?}, expected {TAG}")));
    }
    f.ok(APP, "Harbor lists the artifact", format!("tag {TAG}"));

    // Delete the repository and check the registry no longer serves it.
    send(hb.api(ctx, Method::DELETE, &format!("/projects/{m}/repositories/{REPO}")), APP, "delete repository").await?;
    let reg = Registry::login(ctx, APP, &hb.base, &rname, &rsecret, &repo).await?;
    let status = reg.manifest_status(ctx, APP, &repo, TAG).await?;
    if status != 404 {
        return Err(Fail::new(APP, "repository deleted", format!("the manifest answers HTTP {status} after deleting the repository")));
    }
    f.ok(APP, "repository deleted", "manifest 404");
    Ok(())
}

/// Delete the project (its robot and anything left in it) and check it is gone.
pub async fn cleanup(ctx: &Ctx, f: &mut Flow) -> R<()> {
    let hb = Hb::connect()?;
    let found = sweep(ctx, &Scope::Run(ctx.marker.clone()), true).await?;
    let r = hb.api(ctx, Method::GET, &format!("/projects/{}", ctx.marker)).send().await.map_err(|e| Fail::new(APP, "get project", chain(&e)))?;
    if r.status().as_u16() != 404 {
        return Err(Fail::new(APP, "project deleted", format!("GET answers HTTP {} after deleting", r.status())));
    }
    if !found.is_empty() {
        f.ok(APP, "robot and project deleted", "project 404");
    }
    Ok(())
}

/// Family sweep and residue: tagged projects.
pub async fn sweep(ctx: &Ctx, scope: &Scope, delete: bool) -> R<Vec<String>> {
    let hb = Hb::connect()?;
    let found = hb.projects(ctx, scope).await?;
    if delete {
        for (id, name) in &found {
            hb.remove_project(ctx, *id, name).await?;
        }
    }
    Ok(found.into_iter().map(|(_, n)| format!("harbor project {n}")).collect())
}
